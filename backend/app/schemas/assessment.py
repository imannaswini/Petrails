from typing import List, Optional, Any
from pydantic import BaseModel, Field, model_validator

class UnderwritingIntakeSchema(BaseModel):
    model_config = {"extra": "allow"}
    location: Optional[str] = None
    ownerName: Optional[str] = None
    ownerPhone: Optional[str] = None
    registeredVetClinic: Optional[str] = None
    vaccinationDeclaration: Optional[str] = None
    previousIllnesses: Optional[str] = None
    previousSurgeries: Optional[str] = None
    preExistingConditions: Optional[str] = None
    allergies: Optional[str] = None
    currentMedications: Optional[str] = None
    coverageTier: Optional[str] = None
    coverageLimitInr: Optional[float] = Field(default=None, gt=0)
    deductibleInr: Optional[float] = Field(default=None, ge=0)
    copayPercent: Optional[float] = Field(default=None, ge=0, le=100)
    previousInsurance: Optional[str] = None
    previousClaims: Optional[str] = None
    medicalInformationStatus: Optional[str] = None

    @model_validator(mode="after")
    def validate_deductible(self):
        if self.coverageLimitInr is not None and self.deductibleInr is not None and self.deductibleInr > self.coverageLimitInr:
            raise ValueError("deductibleInr cannot exceed coverageLimitInr")
        return self

class ShapFactorSchema(BaseModel):
    id: str
    name: str
    impact: float = Field(..., description="SHAP feature attribution impact (+/- score)")
    category: str = Field(..., description="Category: Medical History, Age & Breed, Vaccination, Claims, Geography")
    explanation: str
    confidence: Optional[float] = None
    featureName: Optional[str] = None
    featureValue: Optional[Any] = None

class InformationGapSchema(BaseModel):
    id: str
    title: str
    description: str
    questions: List[str]
    status: str = "Pending Request"  # 'Pending Request' | 'Requested' | 'Received' | 'Resolved'
    requestedAt: Optional[str] = None
    responseSummary: Optional[str] = None
    affectsCalibration: bool = True

class DecisionHistoryEntrySchema(BaseModel):
    id: str
    action: str  # 'Approve' | 'Request Information' | 'Refer for Review' | 'Condition Added'
    user: str = "Automated Actuarial Pipeline"
    role: str = "Insurance Professional"
    timestamp: Optional[str] = None
    notes: str
    ruleScoreAtTime: int = 50
    mlScoreAtTime: int = 50

class UnderwriterDecisionBlockSchema(BaseModel):
    recommendation: Optional[str] = "MEDIUM"
    selectedDecision: Optional[str] = None
    underwriterNotes: Optional[str] = ""
    stipulations: Optional[List[str]] = Field(default_factory=list)
    lastModifiedBy: Optional[str] = None
    lastModifiedAt: Optional[str] = None

class AssessmentSchema(BaseModel):
    model_config = {"extra": "allow"}

    id: Optional[str] = Field(default=None, description="Unique assessment identifier (generated by backend if omitted)")
    petId: str = Field(..., description="Linked pet identifier")
    petName: str = Field(..., description="Pet name")
    breed: str
    species: str = "Dog"
    ageText: str = "2 years"
    sex: str = "Male"
    ageYears: Optional[float] = Field(default=None, ge=0.1, le=25)
    weightKg: Optional[float] = Field(default=None, gt=0, le=150)
    underwritingData: Optional[UnderwritingIntakeSchema] = None
    ruleAnalysis: List[dict] = Field(default_factory=list)
    inferenceMode: Optional[str] = None
    modelVersion: Optional[str] = None
    shapBaseValue: Optional[float] = None
    modelAvailable: Optional[bool] = None
    inferenceUnknownInputs: List[str] = Field(default_factory=list)
    dataCompleteness: Optional[float] = None
    policyId: str
    riskLevel: str = "MEDIUM"  # 'LOW' | 'MEDIUM' | 'HIGH'
    combinedScore: int = Field(default=50, ge=0, le=100)
    ruleScore: int = Field(default=50, ge=0, le=100)
    mlScore: int = Field(default=50, ge=0, le=100)
    modelConfidence: int = Field(default=90, description="Confidence percentage e.g. 91")
    calibrationBand: str = "Calibrated ±3.0%"
    informationGapsCount: int = 0
    informationGaps: List[InformationGapSchema] = Field(default_factory=list)
    contributingFactors: List[ShapFactorSchema] = Field(default_factory=list)
    status: str = "Under Review"
    lastUpdated: Optional[str] = None
    createdAt: Optional[str] = None
    updatedAt: Optional[str] = None
    createdByUserId: Optional[str] = None
    createdByEmail: Optional[str] = None
    createdByName: Optional[str] = None
    createdByRole: Optional[str] = None
    authorizedUserIds: List[str] = Field(default_factory=list)
    isDemoSeed: bool = False
    isDeleted: bool = False
    archivedAt: Optional[str] = None
    deletedByUserId: Optional[str] = None
    deletedByName: Optional[str] = None
    previousStatus: Optional[str] = None
    underwriterDecision: Optional[UnderwriterDecisionBlockSchema] = None
    decisionHistory: Optional[List[DecisionHistoryEntrySchema]] = Field(default_factory=list)
    imageUrl: str = "https://images.unsplash.com/photo-1543466835-00a7907e9de1?auto=format&fit=crop&q=80&w=800"

class AssessmentUpdatePayload(BaseModel):
    """Validated payload for editing an existing assessment and its linked clinical/policy inputs."""
    # Pet information
    petName: Optional[str] = Field(default=None, min_length=1, max_length=120)
    species: Optional[str] = Field(default=None, min_length=1, max_length=40)
    breed: Optional[str] = Field(default=None, min_length=1, max_length=120)
    ageYears: Optional[float] = Field(default=None, ge=0.1, le=25.0)
    ageText: Optional[str] = None
    sex: Optional[str] = None
    weightKg: Optional[float] = Field(default=None, gt=0, le=150.0)

    # Medical information (supported by Pet & UnderwritingIntakeSchema)
    preExistingConditions: Optional[str] = None
    previousIllnesses: Optional[str] = None
    previousSurgeries: Optional[str] = None
    allergies: Optional[str] = None
    currentMedications: Optional[str] = None
    vaccinationDeclaration: Optional[str] = None
    previousClaims: Optional[str] = None
    medicalHistory: Optional[List[dict]] = None
    vaccinations: Optional[List[dict]] = None
    medications: Optional[List[dict]] = None
    surgeries: Optional[List[dict]] = None
    claims: Optional[List[dict]] = None

    # Insurance information
    coverageTier: Optional[str] = None
    coverageLimitInr: Optional[float] = Field(default=None, gt=0)
    deductibleInr: Optional[float] = Field(default=None, ge=0)
    copayPercent: Optional[float] = Field(default=None, ge=0, le=100)
    previousInsurance: Optional[str] = None

    # Governance / reassessment control
    reopenForReassessment: bool = False
    editReason: Optional[str] = None

    @model_validator(mode="after")
    def validate_insurance_bounds(self):
        if self.coverageLimitInr is not None and self.deductibleInr is not None and self.deductibleInr > self.coverageLimitInr:
            raise ValueError("deductibleInr cannot exceed coverageLimitInr")
        if self.petName is not None and not self.petName.strip():
            raise ValueError("petName cannot be empty")
        if self.breed is not None and not self.breed.strip():
            raise ValueError("breed cannot be empty")
        return self

class UnderwriterDecisionPayload(BaseModel):
    decision: str = Field(..., description="'Approve' | 'Request Information' | 'Refer for Review'")
    notes: str = Field(default="", description="Actuarial justification and underwriter notes")
    stipulation: Optional[str] = None
    user: Optional[str] = Field(
        default=None,
        description="Deprecated optional field; ignored by backend in favor of verified JWT identity."
    )

class InformationRequestPayload(BaseModel):
    gapTitle: Optional[str] = None
    recipient: str = Field(default="clinic", description="'clinic' | 'owner' | 'both'")
    urgency: str = Field(default="Standard (48h)", description="Turnaround window")
    questions: List[str] = Field(default_factory=list)


class DocumentReviewPayload(BaseModel):
    action: str = Field(..., description="'ACCEPT_CORRECTIONS' | 'DISMISS'")
    acceptedFields: List[str] = Field(default_factory=list)
    reviewNotes: Optional[str] = None
    verifyAccepted: bool = False

